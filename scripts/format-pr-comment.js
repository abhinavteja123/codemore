#!/usr/bin/env node
/* codemore-ignore-file: core-quality-leftover-console, core-bugs-todo-fixme, core-quality-empty-catch */
/* Build / install script — console output IS the user-facing UX during
   postinstall and download-binaries. TODOs surface as inventory elsewhere. */

/**
 * Format a CodeMoreReport (JSON on stdin) as a GitHub PR comment in
 * Markdown on stdout. Intended to be called from the GitHub Action.
 *
 * The comment is structured so the calling LLM (Copilot, Claude Code,
 * Cursor) can read it back as "agentInstructions" + per-issue blocks
 * and propose fixes. The header summary is for humans.
 */

const fs = require('fs');

function readJson(path) {
  return JSON.parse(fs.readFileSync(path, 'utf8'));
}

const SEV_EMOJI = {
  BLOCKER: '🛑',
  CRITICAL: '🔴',
  MAJOR: '🟠',
  MINOR: '🟡',
  INFO: '⚪',
};

const SEV_RANK = { BLOCKER: 5, CRITICAL: 4, MAJOR: 3, MINOR: 2, INFO: 1 };

function buildHeader(r) {
  const s = r.summary;
  const score = s.score;
  const verdict =
    s.bySeverity.BLOCKER > 0 ? '**❌ Blocking issues found.**'
    : s.bySeverity.CRITICAL > 0 ? '**⚠️ Critical issues found.**'
    : s.bySeverity.MAJOR > 0 ? '**🟠 Major issues found.**'
    : '**✅ No blocking issues.**';
  return [
    `## CodeMore Scan — score \`${score}/100\``,
    '',
    verdict,
    '',
    `| Files | LOC | Tech debt | BLOCKER | CRITICAL | MAJOR | MINOR | INFO |`,
    `|--:|--:|--:|--:|--:|--:|--:|--:|`,
    `| ${s.filesAnalyzed} | ${s.linesOfCode} | ${Math.round(s.technicalDebtMinutes)} min | ${s.bySeverity.BLOCKER} | ${s.bySeverity.CRITICAL} | ${s.bySeverity.MAJOR} | ${s.bySeverity.MINOR} | ${s.bySeverity.INFO} |`,
    '',
    `Packs loaded: ${(r.meta?.packsLoaded ?? []).map(p => '`' + p + '`').join(', ')} · Rules evaluated: ${r.meta?.rulesEnabled ?? '?'}`,
    '',
  ].join('\n');
}

function buildIssueBlock(issue) {
  const emoji = SEV_EMOJI[issue.severity] ?? '•';
  const conf = issue.confidence !== undefined ? ` · confidence \`${issue.confidence.toFixed(2)}\`` : '';
  const head = `### ${emoji} \`${issue.id}\` — ${issue.evidence.file}:${issue.evidence.line}${conf}`;

  const body = [head, '', issue.title, ''];

  if (issue.evidence.snippet) {
    body.push('```');
    body.push(issue.evidence.snippet.slice(0, 200));
    body.push('```');
    body.push('');
  }

  body.push('**Why it matters.** ' + issue.whyItMatters);
  body.push('');

  if (issue.suggestedFix) {
    body.push('<details><summary>Suggested fix</summary>');
    body.push('');
    body.push(issue.suggestedFix.instructions);
    if (issue.suggestedFix.verificationCriteria?.length) {
      body.push('');
      body.push('**Verification criteria:**');
      for (const c of issue.suggestedFix.verificationCriteria) body.push(`- [ ] ${c}`);
    }
    body.push('');
    body.push('</details>');
    body.push('');
  }

  body.push(`[Rule docs](${issue.citation}) · suppress with \`${issue.suppression?.directive ?? '// codemore-ignore: ' + issue.id}\``);

  return body.join('\n');
}

function buildAgentSection(report) {
  return [
    '## For the AI agent reading this',
    '',
    '> ' + (report.agentInstructions?.preamble ?? ''),
    '> ',
    '> Ordering hint: ' + (report.agentInstructions?.orderingHint ?? 'blockers → criticals → majors'),
    '> Do not touch: ' + ((report.agentInstructions?.doNotTouch ?? []).map(p => '`' + p + '`').join(', ') || '(none specified)'),
    '',
    `Each issue below has an \`instanceId\`. Apply fixes one at a time. After each fix, ` +
      `call the CodeMore MCP tool \`validate_fix(instanceId, newContent)\` to confirm the rule ` +
      `no longer fires before moving on. If validation fails, retry up to 3 times before escalating.`,
    '',
  ].join('\n');
}

function main() {
  const reportPath = process.argv[2];
  if (!reportPath) {
    process.stderr.write('Usage: node scripts/format-pr-comment.js <codemore-report.json>\n');
    process.exit(2);
  }
  const report = readJson(reportPath);

  const sorted = report.issues.slice().sort(
    (a, b) => SEV_RANK[b.severity] - SEV_RANK[a.severity] || a.evidence.file.localeCompare(b.evidence.file) || a.evidence.line - b.evidence.line,
  );

  const MAX_INLINE = 20;
  const inline = sorted.slice(0, MAX_INLINE);
  const overflow = sorted.length - inline.length;

  const sections = [
    buildHeader(report),
    buildAgentSection(report),
    '---',
    '',
  ];

  if (inline.length === 0) {
    sections.push('_No issues detected. Score is 100/100._');
  } else {
    for (const iss of inline) sections.push(buildIssueBlock(iss));
    if (overflow > 0) {
      sections.push(`_…and ${overflow} more issue(s). Run \`codemore scan .\` locally or expand the report artifact for the full list._`);
    }
  }

  sections.push('');
  sections.push(`<sub>Generated by [CodeMore](https://codemore.dev) v${report.tool?.version ?? '?'} · report schema v${report.schemaVersion}</sub>`);

  process.stdout.write(sections.join('\n') + '\n');
}

main();
